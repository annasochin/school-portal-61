# ---------------------------------------------------------------- сборка

def main():
    doc = docx.Document(str(TEMPLATE))

    # заголовок шаблона → отметка о заполнении
    for p in doc.paragraphs:
        if p.text.strip() == "Шаблон для заполнения":
            set_paragraph(p, "Заполненный вариант: «Цифровая редакция школы» — "
                             "анонс олимпиады, который найдут все")

    # абзацы-поля
    # блок 7: проектное задание (кейс) — шаблонная строка с «…», ищем по началу
    PROJECT_TASK = (
        "«Вы — команда редакции школьного портала № 61. Заказчик — администрация "
        "школы — хочет, чтобы ученики 5–9 классов узнали о реальных олимпиадах этого "
        "сезона и успели подать заявки до дедлайна, а информация лежала в одном "
        "проверенном месте. У вас два занятия. Соберите на портале анонс реальной "
        "олимпиады: отберите 2–3 источника, сверите сроки, опубликуйте страницу с "
        "точными датами и рабочей ссылкой, распечатайте карточку с QR-кодом и дайте "
        "обоснованную рекомендацию: какую олимпиаду классу стоит выбрать первым делом "
        "и почему.»"
    )

    filled = 0
    for p in doc.paragraphs:
        text = p.text.strip()
        if text.startswith("→ «Вы — команда"):
            set_paragraph(p, PROJECT_TASK)
        elif text in PARAGRAPH_FIELDS:
            set_paragraph(p, PARAGRAPH_FIELDS[text])
            filled += 1
        elif text == "→ задача 5 (при необходимости)":
            drop_paragraph(p)          # задач достаточно четырёх
    assert filled == len(PARAGRAPH_FIELDS), f"заполнено абзацев: {filled}"

    # таблицы
    for t_idx, rows in TABLE_FIELDS.items():
        table = doc.tables[t_idx]
        for r_idx, cols in rows.items():
            for c_idx, value in cols.items():
                set_cell(table.rows[r_idx].cells[c_idx], value)

    # маршрут (6.1) — занятие в классе: одна строка, без точек маршрута
    t7 = doc.tables[7]
    set_cell(t7.rows[1].cells[0], "не требуется — занятие в компьютерном кабинете")
    set_cell(t7.rows[1].cells[1], "—")
    set_cell(t7.rows[1].cells[2], "—")
    drop_row(t7, 3)
    drop_row(t7, 2)

    doc.save(str(OUT))
    print(f"OK: {OUT}")


if __name__ == "__main__":
    main()
