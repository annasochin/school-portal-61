# ---------------------------------------------------------------- утилиты

def set_paragraph(p, text):
    """Заменяет содержимое абзаца, сохраняя сам абзац (стиль, место)."""
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    p.add_run(text)


def set_cell(cell, text):
    """Пишет текст в ячейку одной строкой (убирает лишние абзацы)."""
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    set_paragraph(cell.paragraphs[0], text)


def drop_paragraph(p):
    p._element.getparent().remove(p._element)


def drop_row(table, idx):
    tr = table.rows[idx]._tr
    tr.getparent().remove(tr)


